#!/usr/bin/env python3
"""Render LiftLog's editable vector into the existing launcher icon catalogues.

Requires CairoSVG and Pillow. Run with --check to verify generated files without
writing. The Android adaptive and monochrome layers share the SVG's geometry.
"""

import argparse
from io import BytesIO
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

import cairosvg
from PIL import Image, ImageDraw


PROJECT = Path(__file__).resolve().parents[1]
SVG = PROJECT / 'assets/branding/liftlog-icon.svg'
ANDROID = PROJECT / 'android/app/src/main/res'
SVG_NS = '{http://www.w3.org/2000/svg}'


def rounded_path(rect):
    x = float(rect.get('x', 0))
    y = float(rect.get('y', 0))
    width = float(rect.attrib['width'])
    height = float(rect.attrib['height'])
    radius = float(rect.get('rx', 0))
    return (
        f'M{x+radius:g},{y:g} H{x+width-radius:g} '
        f'A{radius:g},{radius:g} 0 0 1 {x+width:g},{y+radius:g} '
        f'V{y+height-radius:g} A{radius:g},{radius:g} 0 0 1 {x+width-radius:g},{y+height:g} '
        f'H{x+radius:g} A{radius:g},{radius:g} 0 0 1 {x:g},{y+height-radius:g} '
        f'V{y+radius:g} A{radius:g},{radius:g} 0 0 1 {x+radius:g},{y:g} Z'
    )


def vector(mark, *, monochrome=False, cropped=False):
    rotation = re.fullmatch(r'rotate\(([-\d.]+) ([-\d.]+) ([-\d.]+)\)', mark.attrib['transform'])
    if rotation is None or any(node.tag != SVG_NS + 'rect' for node in mark):
        raise ValueError('The mark must contain rounded rectangles and a pivot rotation.')
    angle, pivot_x, pivot_y = rotation.groups()
    color = '#FFFFFF' if monochrome else mark.attrib['fill']
    viewport = 640 if cropped else 1024
    size = 24 if cropped else 108
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by tool/generate_app_icons.py from assets/branding/liftlog-icon.svg. -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{size}dp" android:height="{size}dp"',
        f'    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">',
    ]
    if cropped:
        lines.append('    <group android:translateX="-192" android:translateY="-192">')
    lines.append(f'    <group android:rotation="{angle}" android:pivotX="{pivot_x}" android:pivotY="{pivot_y}">')
    lines.extend(f'        <path android:fillColor="{color}" android:pathData="{rounded_path(rect)}" />' for rect in mark)
    lines.append('    </group>')
    if cropped:
        lines.append('    </group>')
    lines.append('</vector>')
    return ('\n'.join(lines) + '\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = ET.fromstring(SVG.read_bytes())
    mark = source.find(f'{SVG_NS}g[@id="mark"]')
    background = source.find(f'{SVG_NS}rect[@id="background"]')
    if mark is None or background is None:
        raise ValueError('The source SVG must define background and mark elements.')
    master = Image.open(BytesIO(cairosvg.svg2png(url=str(SVG), output_width=2048, output_height=2048))).convert('RGB')
    outputs = {}

    def png(path, size, *, circle=False):
        image = master.resize((size, size), Image.Resampling.LANCZOS)
        if circle:
            # A high-resolution mask keeps pre-adaptive round icons crisp.
            mask = Image.new('L', (size * 4, size * 4))
            ImageDraw.Draw(mask).ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=255)
            image = image.convert('RGBA')
            image.putalpha(mask.resize((size, size), Image.Resampling.LANCZOS))
        buffer = BytesIO()
        image.save(buffer, format='PNG', optimize=True)
        outputs[path] = buffer.getvalue()

    for density, size in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)]:
        png(ANDROID / f'mipmap-{density}/ic_launcher.png', size)
        png(ANDROID / f'mipmap-{density}/ic_launcher_round.png', size, circle=True)
    outputs[ANDROID / 'drawable/ic_launcher_foreground.xml'] = vector(mark)
    outputs[ANDROID / 'drawable/ic_launcher_monochrome.xml'] = vector(mark, monochrome=True)
    outputs[ANDROID / 'drawable/ic_liftlog_mark.xml'] = vector(mark, cropped=True)
    outputs[ANDROID / 'drawable/ic_live_workout.xml'] = vector(mark, monochrome=True, cropped=True)
    outputs[ANDROID / 'values/launcher_icon_colors.xml'] = (
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="liftlog_icon_background">{background.attrib["fill"]}</color>\n'
        '</resources>\n'
    ).encode()
    for qualifier in ['anydpi-v26', 'anydpi-v33']:
        themed = '\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />' if qualifier.endswith('33') else ''
        adaptive = (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@color/liftlog_icon_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />'
            f'{themed}\n</adaptive-icon>\n'
        ).encode()
        for name in ['ic_launcher', 'ic_launcher_round']:
            outputs[ANDROID / f'mipmap-{qualifier}/{name}.xml'] = adaptive

    for catalogue in ['ios/Runner/Assets.xcassets/AppIcon.appiconset', 'macos/Runner/Assets.xcassets/AppIcon.appiconset']:
        folder = PROJECT / catalogue
        for item in json.loads((folder / 'Contents.json').read_text())['images']:
            if 'filename' not in item:
                continue
            size = round(float(item['size'].split('x')[0]) * float(item['scale'].removesuffix('x')))
            png(folder / item['filename'], size)
    for name, size in [('Icon-192.png', 192), ('Icon-512.png', 512), ('Icon-maskable-192.png', 192), ('Icon-maskable-512.png', 512)]:
        png(PROJECT / 'web/icons' / name, size)
    png(PROJECT / 'web/favicon.png', 32)
    png(PROJECT / 'assets/branding/liftlog-icon-1024.png', 1024)
    png(PROJECT / 'assets/branding/play-store-icon.png', 512)
    windows_icon = PROJECT / 'windows/runner/resources/app_icon.ico'
    if windows_icon.parent.is_dir():
        buffer = BytesIO()
        master.resize((256, 256), Image.Resampling.LANCZOS).save(buffer, format='ICO',
            sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
        outputs[windows_icon] = buffer.getvalue()

    stale = []
    for path, data in outputs.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                stale.append(str(path.relative_to(PROJECT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if stale:
        print('Regenerate icon assets:\n' + '\n'.join(stale), file=sys.stderr)
        return 1
    print(f'{"Verified" if args.check else "Generated"} {len(outputs)} LiftLog icon assets.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
